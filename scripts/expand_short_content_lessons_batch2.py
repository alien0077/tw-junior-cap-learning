def locate(lesson_id: str):
    for path in (ROOT / "lessons").glob("*/*.json"):
        try:
            if json.loads(path.read_text(encoding="utf-8")).get("id") == lesson_id:
                return path, None
        except json.JSONDecodeError:
            continue
    bundle_path = ROOT / "site/data-lesson-science.json"
    bundle = json.loads(bundle_path.read_text(encoding="utf-8"))
    return bundle_path, next((item for item in bundle if item.get("id") == lesson_id), None)


def main() -> None:
    changed = []
    for lesson_id, body in LESSONS.items():
        path, entry = locate(lesson_id)
        if entry is None:
            entry = json.loads(path.read_text(encoding="utf-8"))
            entry.setdefault("teaching", {})["body"] = [
                {"id": phase, "phase": phase, "heading": heading, "body": text}
                for phase, (heading, text) in zip(PHASES, body)
            ]
            path.write_text(json.dumps(entry, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        else:
            entry.setdefault("teaching", {})["body"] = [
                {"id": phase, "phase": phase, "heading": heading, "body": text}
                for phase, (heading, text) in zip(PHASES, body)
            ]
            bundle = json.loads(path.read_text(encoding="utf-8"))
            path.write_text(json.dumps(bundle, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        changed.append({"lessonId": lesson_id, "file": str(path.relative_to(ROOT)), "bodyCharacters": sum(len(text) for _, text in body)})
    report = {"updatedAt": "2026-09-07", "changedLessons": len(changed), "changed": changed, "authoringRule": "five independently authored units; no shared paragraph or fixed example"}
    out = ROOT / "implementation/reports/short-content-expansion-batch2.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
