def find_questions(lesson_id):
    return sorted(
        p for p in QROOT.glob("*.json")
        if json.loads(p.read_text()).get("lessonId") == lesson_id
    )


def apply_profile(lesson_id, entries):
    paths = find_questions(lesson_id)
    if len(paths) != len(entries):
        raise RuntimeError(f"{lesson_id}: expected {len(entries)} questions, got {len(paths)}")
    for path, (stem, correct, distractors, explanation) in zip(paths, entries):
        data = json.loads(path.read_text())
        title_match = re.search(r"研究「([^」]+)」", data.get("prompt", ""))
        title = title_match.group(1) if title_match else lesson_id
        data["prompt"] = f"在本單元「{title}」的資料判讀中，{stem}"
        choices = [correct] + list(distractors)
        # Rotate correct answer using the stable file order, while keeping all
        # options explicitly tied to the authored unit context.
        shift = int(path.stem.rsplit("-", 1)[-1]) % 4
        choices = choices[shift:] + choices[:shift]
        letters = "ABCD"
        data["options"] = [
            {"id": letters[i], "text": text} for i, text in enumerate(choices)
        ]
        answer_id = letters[choices.index(correct)]
        data["answer"] = {"value": answer_id, "explanation": explanation}
        data["solutionStrategy"] = "先找出本單元的核心關係，再以題幹資料建立判準，逐項核對證據、單位與因果方向。"
        data["solutionSteps"] = [
            f"定位單元：先確認題目要判斷的是「{title}」的核心關係。",
            f"整理證據：從題幹找出與「{title}」直接相關的條件、量或現象。",
            f"推理判斷：依據「{explanation}」核對各選項。",
            "排除干擾：刪除混淆概念、錯誤方向或缺少條件的選項。",
            f"回看答案：確認 {answer_id} 同時符合題幹、單位與本單元的科學意義。",
        ]
        data["updatedAt"] = "2026-09-07"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def main():
    for lesson_id, entries in PROFILES.items():
        apply_profile(lesson_id, entries)
    print(json.dumps({"status": "pass", "lessons": len(PROFILES), "questions": sum(len(v) for v in PROFILES.values())}, ensure_ascii=False))


if __name__ == "__main__":
    main()
