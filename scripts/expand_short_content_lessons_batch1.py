def main() -> None:
    changed = []
    for lesson_id, body in LESSONS.items():
        path = next((p for p in (ROOT / "lessons").glob("*/*.json") if json.loads(p.read_text(encoding="utf-8")).get("id") == lesson_id), None)
        if path is not None:
            data = json.loads(path.read_text(encoding="utf-8"))
            phases = ["hook", "explain", "worked-example", "guided-practice", "transfer", "reflect"]
            data.setdefault("teaching", {})["body"] = [{"id": phase, "phase": phase, "heading": h, "body": text} for phase, (h, text) in zip(phases, body)]
            path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
            changed.append({"lessonId": lesson_id, "file": str(path.relative_to(ROOT)), "bodyCharacters": sum(len(x[1]) for x in body)})
            continue

        # Science content J is stored in the subject bundle rather than a
        # per-lesson file; update that canonical bundle entry in place.
        bundle_path = ROOT / "site/data-lesson-science.json"
        bundle = json.loads(bundle_path.read_text(encoding="utf-8"))
        entry = next((item for item in bundle if item.get("id") == lesson_id), None)
        if entry is None:
            raise FileNotFoundError(lesson_id)
        phases = ["hook", "explain", "worked-example", "guided-practice", "transfer", "reflect"]
        entry.setdefault("teaching", {})["body"] = [{"id": phase, "phase": phase, "heading": h, "body": text} for phase, (h, text) in zip(phases, body)]
        bundle_path.write_text(json.dumps(bundle, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        changed.append({"lessonId": lesson_id, "file": str(bundle_path.relative_to(ROOT)), "bodyCharacters": sum(len(x[1]) for x in body)})
    report = {"updatedAt": "2026-09-07", "changedLessons": len(changed), "changed": changed, "authoringRule": "five independently authored units; no shared paragraph or fixed example"}
    out = ROOT / "implementation/reports/short-content-expansion-batch1.json"
    out.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
