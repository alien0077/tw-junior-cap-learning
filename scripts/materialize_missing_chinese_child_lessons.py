def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    report = []
    for unit_id, item in UNITS.items():
        path = OUT / f"lesson-chinese-content-{unit_id}.json"
        lesson = make_lesson(unit_id, item)
        path.write_text(json.dumps(lesson, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        report.append({"unitId": unit_id, "lessonPath": str(path.relative_to(ROOT)), "reviewStatus": "draft"})
    report_path = ROOT / "implementation" / "reports" / "missing-chinese-child-endpoints.json"
    report_path.write_text(json.dumps({"generatedAt": TODAY, "count": len(report), "items": report}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "pass", "materialized": len(report), "reviewStatus": "draft"}, ensure_ascii=False))


