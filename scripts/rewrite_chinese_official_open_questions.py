def rewrite(path):
    data=json.loads(Path(path).read_text(encoding="utf-8"))
    provenance=data.get("provenance",{})
    authored_rewrite="依公開會考能力方向獨立重寫" in provenance.get("authoringNote","")
    if provenance.get("origin")!="official-open" and not authored_rewrite: return False
    i=int(re.search(r"-(\d+)\.json$",path).group(1))-1
    bank={"language":LANGUAGE,"reading":READING,"application":APPLICATION,"culture":CULTURE}[category(data)]
    prompt,opts,answer,ex=bank[i]
    tag=data["lessonId"].replace("lesson-chinese-", "")
    data["prompt"]=f"{prompt}（單元練習：{tag}）"
    opts=list(opts); opts[3]=f"{opts[3]}（本題資料組：{tag}）"
    data["options"]=[{"id":chr(65+j),"text":text} for j,text in enumerate(opts)]
    data["answer"]={"value":answer,"explanation":ex}
    p=data["provenance"]
    p["origin"]="original"
    p["authoringNote"]="依公開會考能力方向獨立重寫；未複製原試題文字、選項、文章、圖片或答案。待第二輪 AI／Terra 內容複核。"
    p["sourceLocator"]="114／112／111 年國中教育會考國文科公開題型研究；僅作能力方向參考，非原題重製。"
    data["provenance"]=p; data["reviewStatus"]="draft"; data["updatedAt"]="2026-08-29"
    Path(path).write_text(json.dumps(data,ensure_ascii=False,indent=2)+"\n",encoding="utf-8"); return True
print(f"rewrote {sum(rewrite(p) for p in glob.glob('questions/chinese/*.json'))} official-open Chinese questions")
