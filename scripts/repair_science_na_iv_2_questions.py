for index, (prompt, options, answer, explanation, strategy) in enumerate(DATA, 1):
    path = DATA_DIR / f"question-science-content-na-iv-2-{index}.json"
    record = json.loads(path.read_text())
    correct_text = options[ord(answer) - 65]
    target_letters=["A", "B", "C", "D", "B", "C", "D", "A", "C", "B"]
    target=target_letters[index-1]
    distractors=[x for x in options if x != correct_text]
    ordered=[]; di=0
    for letter in ["A", "B", "C", "D"]:
        if letter == target: ordered.append(correct_text)
        else: ordered.append(distractors[di]); di += 1
    record.update({"prompt": prompt, "options": [{"id": chr(65+i), "text": x} for i, x in enumerate(ordered)], "answer": {"value": target, "explanation": explanation + f" 正確答案為選項 {target}：「{correct_text}」。"}, "solutionStrategy": strategy, "solutionSteps": ["圈出功率、時間、待機、效率、尖峰或基準等關鍵詞。", "統一用電量、服務需求與比較期間的條件。", f"套用原理：{explanation}", f"排除只看外觀、單日或忽略需求差異的選項，保留「{correct_text}」。", f"回查答案「{correct_text}」是否符合節能公式與可量測成效。"], "reviewStatus": "draft"})
