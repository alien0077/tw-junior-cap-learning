def build_question(unit, index, item):
    prompt, options, answer, explanation = item
    return {
        "id": f"question-math-content-{unit}-{index}",
        "subject": "math",
        "type": "single-choice",
        "prompt": prompt,
        "options": [
            {"id": chr(ord("A") + i), "text": text} for i, text in enumerate(options)
        ],
        "knowledgeIds": [UNITS[unit]["kg"]],
        "difficulty": "medium",
        "answer": {"value": answer, "explanation": explanation},
        "provenance": {
            "origin": "original",
            "license": "All rights reserved",
            "sourceUrl": SOURCE_URL,
            "sourceLocator": (
                "高雄市立鹽埕國民中學 114 學年度第二學期第一次段考數學科；"
                f"參考 {UNITS[unit]['title']} 題型與官方課綱 KG {UNITS[unit]['kg']}"
            ),
            "authoringNote": (
                "Substantive rewrite with new values, contexts, options, and explanations; "
                "no reproduction of public-exam wording, figures, or answer key. "
                "待第二輪 AI／Terra 內容複核。"
            ),
        },
        "reviewStatus": "draft",
        "updatedAt": "2026-08-28",
        "lessonId": UNITS[unit]["lesson"],
    }


def main():
    count = 0
    for unit, config in UNITS.items():
        for index, item in enumerate(config["items"], start=1):
            path = QUESTION_DIR / f"question-math-content-{unit}-{index}.json"
            path.write_text(
                json.dumps(build_question(unit, index, item), ensure_ascii=False, indent=2)
                + "\n",
                encoding="utf-8",
            )
            count += 1
    print(f"replaced {count} similarity/geometry template questions")


if __name__ == "__main__":
    main()
