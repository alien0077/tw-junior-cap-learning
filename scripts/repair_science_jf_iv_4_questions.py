    record.update({"prompt": prompt, "options": [{"id": chr(65+i), "text": x} for i, x in enumerate(arranged)], "answer": {"value": target, "explanation": explanation + f" 正確答案為選項 {target}：「{correct_text}」。"}, "solutionStrategy": strategy, "solutionSteps": ["圈出塑膠性質、標誌、使用情境、回收或環境影響。", "判斷材料結構、使用條件與廢棄物流的關係。", f"套用原理：{explanation}", f"排除把所有塑膠視為相同或忽略生命週期的選項，保留「{correct_text}」（選項 {target}）。", f"回查答案「{correct_text}」是否符合塑膠性質與實際證據。"], "reviewStatus": "draft"})
