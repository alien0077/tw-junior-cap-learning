def main() -> int:
    changed = 0
    for key, items in REPAIRS.items():
        subject, unit_id = key.split("-", 1)
        path = ROOT / "lessons" / subject / f"lesson-{subject}-{unit_id}.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        data.setdefault("interactive", {})["steps"] = steps(items)
        data["reviewStatus"] = "draft"
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        changed += 1
    report = ROOT / "implementation/reports/repeated-interactive-repair.json"
    report.write_text(json.dumps({"changedLessons": changed, "repairGroups": len(REPAIRS), "status": "pass" if changed == len(REPAIRS) else "fail"}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"changedLessons": changed, "repairGroups": len(REPAIRS), "status": "pass" if changed == len(REPAIRS) else "fail"}, ensure_ascii=False))
    return 0 if changed == len(REPAIRS) else 1


if __name__ == "__main__":
    raise SystemExit(main())
